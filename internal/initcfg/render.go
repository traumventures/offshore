package initcfg

import (
	"fmt"
	"strconv"
	"strings"
)

// Render writes the detected configuration as commented TOML.
func (d *Detection) Render() string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	comment := func(s string) {
		if s != "" {
			w("# %s\n", s)
		}
	}
	w("# cloudsourced repository configuration, generated by `cloudsourced init`.\n")
	w("# Review it: every detected item is explained in the comment above it.\n")
	if d.Rust {
		ws := d.Workspace
		if ws == "" {
			ws = "the repository root"
		}
		w("# Cargo workspace: %s.\n", ws)
	}
	w("version = 1\n\n")

	w("[resources]                    # per session\n")
	comment(d.CPUNote)
	w("cpu = %d\n", d.CPU)
	w("memory = \"4G\"                 # reservation, not a limit; refined from measured peaks\n\n")

	w("[environment]\n")
	comment(d.ImageWhy)
	w("image = %s\n", quote(d.Image))
	if d.Linker != "" {
		w("linker = %s                # faster linking of Rust binaries\n", quote(d.Linker))
	}
	if d.Toolchain != "" {
		w("\n[environment.toolchains]\n")
		comment(d.ToolchainNote)
		w("rust = %s\n", quote(d.Toolchain))
	}
	if len(d.Apt) > 0 {
		w("\n[environment.packages]\n")
		comment(d.AptWhy)
		w("apt = %s\n", list(d.Apt, 7))
	}
	for _, s := range d.Setup {
		w("\n[[environment.setup]]\n")
		comment(s.Comment)
		w("run = %s\n", quote(s.Run))
	}
	if len(d.Env) > 0 {
		w("\n[environment.env]\n")
		for _, e := range d.Env {
			comment(e.Why)
			w("%s = %s\n", key(e.Key), quote(e.Value))
		}
	}
	for _, s := range d.Services {
		w("\n[services.%s]\n", key(s.Name))
		comment(s.Why)
		w("image = %s\n", quote(s.Image))
		if len(s.Env) > 0 {
			var kv []string
			for _, e := range s.Env {
				kv = append(kv, key(e.Key)+" = "+quote(e.Value))
			}
			w("env = { %s }\n", strings.Join(kv, ", "))
		}
		if s.Port > 0 {
			w("port = %d\n", s.Port)
		}
		if len(s.Command) > 0 {
			w("command = %s\n", list(s.Command, 0))
		}
	}
	if len(d.Secrets) > 0 {
		w("\n[secrets]                      # resolved locally per run, never stored remotely\n")
		for _, s := range d.Secrets {
			comment(s.Why)
			w("%s = %s\n", key(s.Key), quote(s.Value))
		}
		if len(d.GitDeps) > 0 {
			w("# git dependencies: %s\n", strings.Join(d.GitDeps, ", "))
		}
	}
	if len(d.BuildCache) > 0 {
		w("\n[cache.target]\n")
		w("scope = \"slot\"                 # stays on the machine (24 h), never synchronised\n")
		w("paths = %s\n", list(d.BuildCache, 0))
		if d.Rust {
			w("prune = \"rust\"\n")
		}
	}
	if len(d.DepsCache) > 0 {
		w("\n[cache.deps]\n")
		w("scope = \"machine\"              # shared by the sessions of a machine\n")
		w("paths = %s\n", list(d.DepsCache, 0))
	}
	if d.Rust {
		w("\n[cache.sccache]               # shared compiler cache across machines\n")
		w("scope = \"global\"\n")
		w("tool = \"sccache\"\n")
		w("\n[tool.cargo]\n")
		w("# subcommands that only touch the local checkout or your account run locally\n")
		w("local = %s\n", list(d.CargoLocal, 0))
		w("# environment variables forwarded to remote runs")
		if d.EnvWhy != "" {
			w(" (%s)", d.EnvWhy)
		}
		w("\nenv = %s\n", list(d.CargoEnv, 6))
	}
	if len(d.Notes) > 0 {
		w("\n# Detected but not adopted:\n")
		for _, n := range d.Notes {
			w("#   - %s\n", n)
		}
	}
	return b.String()
}

// quote renders a TOML string: multi-line values as literal strings, so
// shell backslashes stay as written.
func quote(s string) string {
	if strings.Contains(s, "\n") && !strings.Contains(s, "'''") {
		return "'''\n" + s + "\n'''"
	}
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '"':
			b.WriteString(`\"`)
		case '\\':
			b.WriteString(`\\`)
		case '\n':
			b.WriteString(`\n`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 0x20 {
				fmt.Fprintf(&b, `\u%04X`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}

func key(k string) string {
	for _, r := range k {
		if !(r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '_' || r == '-') {
			return strconv.Quote(k)
		}
	}
	return k
}

// list renders a string array, wrapping after perLine items (0: one line).
func list(items []string, perLine int) string {
	var b strings.Builder
	b.WriteByte('[')
	for i, it := range items {
		if i > 0 {
			b.WriteString(",")
			if perLine > 0 && i%perLine == 0 {
				b.WriteString("\n       ")
			} else {
				b.WriteString(" ")
			}
		}
		b.WriteString(quote(it))
	}
	b.WriteByte(']')
	return b.String()
}
